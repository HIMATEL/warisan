TITLE PEMBAGIAN 2 DATA 8 BIT CARA 1
; 8 BIT BH DIBAGI 8 BIT BL, DENGAN HASIL DI DL DAN SISA DI DH    
; METODE PENGURANGAN BERULANG

.MODEL SMALL
.STACK 100H
.DATA

.CODE
MAIN PROC      
    MOV DL,BH   ; BH DIISI KE DL
    MOV DH,0    ; PASTIKAN DH SEBAGAI PENYIMPAN SISA BAGI DIKOSONGKAN
    CMP BL,1    ; PERIKSA APAKAH BL SEBAGAI PEMBAGI = 1 
    JE AKH      ; IF BL=1, LONCAT KE AKHIR KARENA BH MENJADI HASIL
    CMP BH,BL   ; PERIKSA APAKAH BH<BL
    JB AKH      ; IF BH<BL, LONCAT KE AKHIR LANGSUNG MENJADI SISA BAGI
    MOV DL,0    ; AL HARUS DIKOSONGKAN TERLEBIH DAHULU UNTUK SIAP SIAP MENGHITUNG
    MOV DH,BH   ; SUPAYA BH UTUH DAN YANG DIKURANGI ADALAH AH

LUP:CMP DH,BL   ; PEMBAGI BUKANLAH 1 DAN YANG DIBAGI MASIH > PEMBAGI
    JB AKH      ; IF DH SEBAGAI YANG DIBAGI <BL, LONCAT KE AKHIR, KARENA LANGSUNG JADI SISA BAGI
    SUB DH,BL   ; LAKUKAN PENGURANGAN 
    INC DL      ; COUNTER PENGHITUNG HARUS DINAIKKAN
    JMP LUP     ; LONCAT KE LUP JIKA HASILNYA MASIH LEBIH DARI 7
    
AKH:MOV AH,4CH
    INT 21H
    
MAIN ENDP
ENDP MAIN  
