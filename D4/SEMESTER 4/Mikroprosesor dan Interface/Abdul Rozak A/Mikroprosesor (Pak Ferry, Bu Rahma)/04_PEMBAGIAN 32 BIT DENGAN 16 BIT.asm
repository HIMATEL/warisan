TITLE 04_PEMBAGIAN 32 BIT DENGAN 16 BIT
.MODEL SMALL 
.STACK 100H
.DATA
HASILBAGI DW 0,0
SISABAGI DW 0
.CODE
MAIN PROC
     MOV AX,@DATA
     MOV DS,AX
     
     MOV DX,0
     MOV AX,BX
     ADD AX,CX
     JZ  SKIP
     ADD SI,0
     JZ  SKIP
     MOV AX,0
     
LUP: SUB CX,SI
     SBB BX,0
     ADD DX,1
     ADC AX,0
     CMP BX,0
     JA  LUP
     CMP CX,SI
     JAE LUP
     MOV [SISABAGI],CX
     MOV [HASILBAGI],DX
     MOV [HASILBAGI+2],AX
SKIP: 
     MOV AH,4CH
     INT 21H
     MAIN ENDP
END MAIN