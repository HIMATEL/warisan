TITLE LAB04 NO5
.MODEL SMALL
.STACK 100H

.DATA
DAT DB 24H,43H,65H,7,43H,75H,76H,6
DB 54H,65H,76H,7,26H,43H,45H,7
DB 65H,67H,42H,6,43H,56H,75H,7
DB 65H,66H,77H,7,67H,66H,55H,5
DB 76H,75H,74H,7
SUM DB 5 DUP(0)

.CODE
MAIN PROC
MOV CX,@DATA
MOV DS,CX
MOV SI,0

SATU:   MOV AL,[SUM+0]
ADD AL,[DAT+SI]
MOV [SUM+0],AL
INC SI
MOV AL,[SUM+1]
ADC AL,[DAT+SI]
MOV [SUM+1],AL
INC SI
MOV AL,[SUM+2]
ADC AL,[DAT+SI]
MOV [SUM+2],AL
INC SI
MOV AL,[SUM+3]
ADC AL,[DAT+SI]
MOV [SUM+3],AL
MOV AL,[SUM+4]
ADC AL,0
MOV [SUM+4],AL
CALL KOREKSI
INC SI
CMP SI,36
JNZ SATU

MOV AH,4CH
INT 21H

KOREKSI PROC
MOV CL,[SUM+0]
MOV CH,[SUM+1]
MOV BL,[SUM+2]
MOV BH,[SUM+3]
MOV AL,[SUM+4]
MOV DL,CL
AND DL,0FH
CMP DL,7
JBE L1
ADD CX,8
ADC BX,0

L1:     MOV DL,CL
AND DL,0F0H
CMP DL,70H
JBE L2
ADD CX,80H
ADC BX,0

L2:     MOV DH,CH
AND DH,0FH
CMP DH,7
JBE L3
ADD CH,8
ADC BX,0

L3:     MOV DH,CH
AND DH,0F0H
CMP DH,70H
JBE L4
ADD CH,80H
ADC BX,0

L4:     MOV DL,BL
AND DL,0FH
CMP DL,7
JBE L5
ADD BL,8
ADC BH,0

L5:     MOV DL,BL
AND DL,0F0H
CMP DL,70H
JBE L6
ADD BL,80H
ADC BH,0

L6:     MOV DH,BH
AND DH,0FH
CMP DH,7
JBE L7
ADD BH,8
ADC AX,0

L7:     MOV DH,BH
AND DH,0F0H
CMP DH,70H
JBE L8
ADD BH,80H
ADC AX,0

L8:     MOV DL,AL
AND DL,0FH
CMP DL,7
JBE L9
ADD AL,8
ADC AH,0

L9:     MOV [SUM+0],CL
MOV [SUM+1],CH
MOV [SUM+2],BL
MOV [SUM+3],BH
MOV [SUM+4],AL
RET

KOREKSI ENDP
END MAIN


