TITLE 02_PERKALIAN 16 BIT DENGAN 16 BIT
.MODEL SMALL  ;CH*CL=DX
.STACK 100H
.DATA
.CODE
MAIN PROC
     MOV AX,@DATA
     MOV DS,AX
     
     MOV DX,0
     ADD CL,0
     JZ  SKIP
     
LUP: ADD DL,CH
     ADC DH,0
     DEC CL
     JNZ LUP
SKIP: 
     MOV AH,4CH
     INT 21H
     MAIN ENDP
END MAIN