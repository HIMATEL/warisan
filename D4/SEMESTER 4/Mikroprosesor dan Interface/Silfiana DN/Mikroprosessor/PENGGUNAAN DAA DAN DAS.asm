TITLE CONTOH PENGGUNAAN DAA DAN DAS
.MODEL SMALL
.STACK 100H

.DATA
    ANGKA1 DB 9     ; ANGKA PERTAMA (DALAM FORMAT DESIMAL)
    ANGKA2 DB 5     ; ANGKA KEDUA (DALAM FORMAT DESIMAL)
    HASIL DB ?      ; VARIABEL UNTUK MENYIMPAN HASIL OPERASI ARITMATIKA

.CODE
    MAIN PROC
        MOV AX, @DATA
        MOV DS, AX

        ; TAMBAHKAN ANGKA1 DAN ANGKA2
        MOV AL, ANGKA1     ; LOAD ANGKA PERTAMA KE DALAM REGISTER AL
        ADD AL, ANGKA2     ; TAMBAHKAN ANGKA KEDUA KE DALAM REGISTER AL
        DAA                ; SESUAIKAN HASIL PENJUMLAHAN DALAM FORMAT DESIMAL
        MOV HASIL, AL      ; SIMPAN HASIL KE DALAM VARIABEL 'HASIL'

        ; TAMPILKAN HASIL PENJUMLAHAN
        MOV DL, HASIL      ; LOAD HASIL KE DALAM REGISTER DL (UNTUK TAMPILKAN)
        ADD DL, 30H        ; KONVERSI HASIL KE ASCII
        MOV AH, 02H        ; SERVICE DOS UNTUK MENAMPILKAN KARAKTER
        INT 21H            ; PANGGIL SERVICE DOS

        ; KURANGKAN ANGKA1 DENGAN ANGKA2
        MOV AL, ANGKA1     ; LOAD ANGKA PERTAMA KE DALAM REGISTER AL
        SUB AL, ANGKA2     ; KURANGKAN ANGKA KEDUA DARI ANGKA PERTAMA DI DALAM REGISTER AL
        DAS                ; SESUAIKAN HASIL PENGURANGAN DALAM FORMAT DESIMAL
        MOV HASIL, AL      ; SIMPAN HASIL KE DALAM VARIABEL 'HASIL'

        ; TAMPILKAN HASIL PENGURANGAN
        MOV DL, HASIL      ; LOAD HASIL KE DALAM REGISTER DL (UNTUK TAMPILKAN)
        ADD DL, 30H        ; KONVERSI HASIL KE ASCII
        MOV AH, 02H        ; SERVICE DOS UNTUK MENAMPILKAN KARAKTER
        INT 21H            ; PANGGIL SERVICE DOS

        MOV AH, 4CH        ; SERVICE DOS UNTUK KELUAR DARI PROGRAM
        INT 21H            ; PANGGIL SERVICE DOS
    MAIN ENDP
END MAIN
