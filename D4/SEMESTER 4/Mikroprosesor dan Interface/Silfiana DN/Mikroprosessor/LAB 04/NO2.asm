TITLE LAB04 NO2
.MODEL SMALL
.STACK 100H
.DATA
BM1 DW 1663H,7347H,6351H,4324H,5632H,4423H,1557H,4700H,4602H,7535H
BM2 DW 3437H,4346H,3463H,3472H,4443H,2762H,4023H,6723H,3225H,6251H
BM3 DW 10 DUP(0)
BM4 DB 10 DUP(0)

.CODE
MAIN PROC
MOV AX,@DATA
MOV DS,AX

MOV AX,0
MOV CX,0
MOV DX,0
MOV SI,0

LUP: MOV CL,0
MOV DX,[BM1+SI]
ADD DX,[BM2+SI]
ADC CL,0

MOV AL,DL
AND AL,0FH
CMP AL,08H
JB  LUP1
ADD DL,08H
ADC DH,0

LUP1:MOV AL,DL
AND AL,0F0H
CMP AL,80H
JB  LUP2
ADD DL,80
ADC DH,0

LUP2:MOV AL,DH
AND AL,0FH
CMP AL,08H
JB  LUP3
ADD DH,08H
ADC CL,0

LUP3:MOV AL,DH
AND AL,0F0H
CMP AL,80H
JB  LUP4
ADD DH,80H
ADC CL,0

LUP4:MOV [BM3+SI],DX
MOV [BM4+SI],CL

INC SI
INC SI
CMP SI,0AH
JB LUP

MOV AH,4CH
INT 21H

MAIN ENDP
END MAIN

