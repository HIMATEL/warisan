TITLE P9_PERKALIAN_16BIT_CR5 
;INPUT BX:CX DAN OUTPUT DATA AREA 'HASIL'
.MODEL SMALL
.STACK 100H
.DATA
HASIL DD 0
.CODE
MAIN PROC
        MOV AX,@DATA
        MOV DS,AX

        ADD BX,0 ;INPUT BX
        ADD CX,0 ;INPUT CX
        MOV AX,CX
        MUL BX

        ;HASIL AX:DX
        MOV [HASIL],AX
        MOV [HASIL+2],DX

        MOV AH,4CH
        INT 21H
MAIN    ENDP
END MAIN