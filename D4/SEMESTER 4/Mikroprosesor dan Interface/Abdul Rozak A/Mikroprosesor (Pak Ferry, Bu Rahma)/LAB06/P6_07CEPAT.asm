.MODEL SMALL
.STACK 100H

.DATA
d1 DW 37657 ; INPUT DECIMAL

.CODE
MAIN PROC FAR
    MOV AX, @DATA
    MOV DS, AX ; LOAD VALUE
    MOV AX, d1 ; KONVERSI VALUE
    CALL PRINT ; MEMANGGIL METODE PRINT
    MOV AH, 4CH
    INT 21H ; STOP

PRINT PROC
    MOV CX, 0
    MOV DX, 0

label1:
    CMP AX, 0
    JE print1 ; JIKA NILAI INPUT=0, MAKA PRINT SELESAI

    MOV BX, 16 ; UNTUK DIBAGI 16
    DIV BX
    PUSH DX ; PUSH KE STACK
    INC CX ; INCREMENT COUNTER
    PUSH DX
    JMP label1

print1:
    CMP CX, 0
    JE exit ; JIKA COUNTER=0, PROGRAM TERHENTI

    POP DX ; MEMUNCULKAN NILAI PALING TINGGI DARI STACK
    ADD DX, 48 ; KONVERSI KE KODE ASCII
    MOV AH, 02H ; PRINT CHAR
    INT 21H
    DEC CX
    JMP print1

exit:
    RET
PRINT ENDP

END MAIN
