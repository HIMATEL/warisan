TITLE LAB NO6
.MODEL SMALL
.STACK 100H
.DATA

.CODE
MAIN PROC
MOV AX,@DATA
MOV DS,AX

MOV SI,0
MOV AX,0
LUP:    ADD AL,37H
ADC AH,0
MOV CL,AL
AND CL,0FH
CMP CL,08H
JB  LUP1
ADD AL,08H
ADC AH,0

LUP1:   MOV CL,AL
AND CL,0F0H
CMP CL,80H
JB  LUP2
ADD AL,80H
ADC AH,0

LUP2:   MOV CL,AH
AND CL,0FH
CMP CL,08H
JB  LUP3
ADD AH,08H

LUP3:   MOV DX,AX
INC SI
CMP SI,0AH
JB  LUP

MOV AH,4CH
INT 21H
MAIN ENDP
END MAIN


